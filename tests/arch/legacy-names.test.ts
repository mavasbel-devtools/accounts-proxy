// Release-gate naming law (AGENTS.md §7): the project is accounts-proxy (renamed 2026-10-16 from its former name,
// docs/reference/2026-10-16-14-40-project-rename.md). No tracked path or live file may carry the former product name,
// its environment-variable prefix or the generic word for what the project used to call itself; OpenRouter (a
// provider) is not that word. Exempt: historical records, which keep what was true when they were written (decision
// Q2): dated docs, recorded provider exchanges, vendored sources, the rename script and this test. Generated model
// data (`// GENERATED by scripts/evidence/gateway-snapshots.ts`) is checked for the product name only: its vendors'
// model names and descriptions use the generic word for their own products.
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..", "..");

const HISTORICAL = [
  /^docs\/(plans|research|reference|sessions|issues|temp)\//,
  /^tests\/fixtures\/captures\//,
  /\/tests\/reference\/plugin-[0-9a-f]+\//,
  /^scripts\/evidence\/rename-project\.ts$/,
  /^tests\/arch\/legacy-names\.test\.ts$/,
];
// Historical file names that live documents link to.
const KEPT_NAMES = /2026-10-06-00-23-inference-router-plan|llm-router-from-auth-plugins/g;
const PRODUCT = /inference[-_ ]router/i;
const GENERIC = [/(?<![Oo]pen)[Rr]outers?/, /(?<!OPEN)ROUTER/, /(?<![A-Za-z0-9_-])rtr_/];
const GENERATED = "// GENERATED by scripts/evidence/gateway-snapshots.ts";

export function offences(path: string, text: string): string[] {
  if (HISTORICAL.some((r) => r.test(path))) return [];
  const found: string[] = [];
  const pathText = path.replace(KEPT_NAMES, "");
  if (PRODUCT.test(pathText) || GENERIC.some((r) => r.test(pathText))) found.push(`${path}: path`);
  const generated = text.startsWith(GENERATED);
  text.split("\n").forEach((line, index) => {
    const kept = line.replace(KEPT_NAMES, "");
    if (PRODUCT.test(kept) || (!generated && GENERIC.some((r) => r.test(kept)))) found.push(`${path}:${index + 1}: ${line.trim().slice(0, 120)}`);
  });
  return found;
}

describe("legacy names", () => {
  test("the check: flags the former names in live files and paths, exempts history, OpenRouter and vendor model data", () => {
    const old = ["inference", "router"].join("-");
    expect(offences("README.md", `run ${old} serve`)).toEqual([`README.md:1: run ${old} serve`]);
    expect(offences("a.ts", `${["INFERENCE", "ROUTER"].join("_")}_HOME`)).toHaveLength(1);
    expect(offences("a.ts", "the Router token\nx-router-lossy\nconst s = `rtr_${hash}`")).toHaveLength(3);
    expect(offences("apps/router/src/a.ts", "")).toEqual(["apps/router/src/a.ts: path"]);
    expect(offences("a.ts", "OpenRouter openrouter OPENROUTER_SPEC provider-openrouter")).toEqual([]);
    expect(offences("README.md", "[plan](docs/plans/2026-10-06-00-23-inference-router-plan.md)")).toEqual([]);
    expect(offences(`docs/plans/x.md`, old)).toEqual([]);
    expect(offences("tests/fixtures/captures/p0-live/x.json", old)).toEqual([]);
    expect(offences("packages/p/tests/reference/plugin-abc123/x.ts", old)).toEqual([]);
    expect(offences("packages/p/src/domain/builtin-models.ts", `${GENERATED}\n"Auto Router"`)).toEqual([]);
    expect(offences("packages/p/src/domain/builtin-models.ts", `${GENERATED}\n${old}`)).toHaveLength(1);
    expect(offences("packages/p/src/domain/builtin-models.ts", `"Auto Router"`)).toHaveLength(1);
  });

  test("no tracked live file or path carries a former name", () => {
    const listed = Bun.spawnSync(["git", "-C", root, "ls-files", "-z"]);
    expect(listed.exitCode).toBe(0);
    const files = listed.stdout.toString().split("\0").filter(Boolean);
    expect(files.length).toBeGreaterThan(500);
    expect(files.flatMap((path) => offences(path, readFileSync(join(root, path), "utf8")))).toEqual([]);
  });
});
