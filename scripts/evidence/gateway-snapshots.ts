// Plan P4.6 rule G5: generate each gateway's built-in model list from the committed vendor lists in
// docs/reference/specs/ (provenance and SHA-256 in manifest.json), through the same parsers the live catalogs use.
// Plan 2026-10-16 rule M4: also the built-in copy of the reference model catalog (models.opencode.ai).
// Usage: bun scripts/evidence/gateway-snapshots.ts   (rewrites packages/provider-*/src/domain/builtin-models.ts and
// apps/proxy/src/adapters/outbound/builtin-model-reference.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseModels as parseCheaper } from "@accounts-proxy/provider-cheaper-inference/domain/cheaper-inference.ts";
import type { GatewayModel } from "@accounts-proxy/provider-gateway/domain/gateway.ts";
import { parseReference, referenceRecord } from "@accounts-proxy/core/domain/model-details.ts";
import { opencodeModels, referenceFormats } from "@accounts-proxy/provider-opencode/domain/opencode.ts";
import { parseModels as parseOpenRouter } from "@accounts-proxy/provider-openrouter/domain/openrouter.ts";

const root = join(import.meta.dir, "..", "..");
const specs = join(root, "docs", "reference", "specs");
const spec = (file: string): unknown => JSON.parse(readFileSync(join(specs, file), "utf8"));
const manifest = spec("manifest.json") as { file: string; url: string; sha256: string; extractSha256?: string; fetchedAt: string }[];
const provenance = (files: readonly string[]) =>
  files
    .map((f) => {
      const m = manifest.find((e) => e.file === f)!;
      return `//   ${f} (${m.url}, fetched ${m.fetchedAt}, sha256 ${m.extractSha256 ?? m.sha256})`;
    })
    .join("\n");

function write(pkg: string, constant: string, models: readonly GatewayModel[], files: readonly string[]): void {
  const body = models.map((m) => `  ${JSON.stringify(m)},`).join("\n");
  const text = `// GENERATED by scripts/evidence/gateway-snapshots.ts (plan P4.6 rule G5); do not edit. Built-in model list from:
${provenance(files)}
import type { GatewayModel } from "@accounts-proxy/provider-gateway/domain/gateway.ts";

export const ${constant}: readonly GatewayModel[] = [
${body}
];
`;
  const path = join(root, "packages", pkg, "src", "domain", "builtin-models.ts");
  writeFileSync(path, text);
  console.log(`${pkg}: ${constant} ${models.length} models`);
}

const reference = parseReference(spec("models-opencode-reference.json"));
write("provider-openrouter", "OPENROUTER_BUILTIN", parseOpenRouter(spec("openrouter-models.json")), ["openrouter-models.json"]);
write("provider-cheaper-inference", "CHEAPER_BUILTIN", parseCheaper(spec("cheaper-inference-public-models.json")), ["cheaper-inference-public-models.json"]);
const zen = opencodeModels(spec("opencode-zen-models.json"), referenceFormats(reference, "opencode"));
const go = opencodeModels(spec("opencode-go-models.json"), referenceFormats(reference, "opencode-go"));
const opencodeFiles = ["opencode-zen-models.json", "opencode-go-models.json", "models-opencode-reference.json"];
const path = join(root, "packages", "provider-opencode", "src", "domain", "builtin-models.ts");
const line = (m: GatewayModel) => `  ${JSON.stringify(m)},`;
writeFileSync(
  path,
  `// GENERATED by scripts/evidence/gateway-snapshots.ts (plan P4.6 rule G5); do not edit. Built-in model lists from:
${provenance(opencodeFiles)}
import type { GatewayModel } from "@accounts-proxy/provider-gateway/domain/gateway.ts";

export const ZEN_BUILTIN: readonly GatewayModel[] = [
${zen.map(line).join("\n")}
];

export const GO_BUILTIN: readonly GatewayModel[] = [
${go.map(line).join("\n")}
];
`,
);
console.log(`provider-opencode: ZEN_BUILTIN ${zen.length} models, GO_BUILTIN ${go.length} models`);

const record = referenceRecord(reference);
writeFileSync(
  join(root, "apps", "proxy", "src", "adapters", "outbound", "builtin-model-reference.ts"),
  `// GENERATED by scripts/evidence/gateway-snapshots.ts (plan 2026-10-16 rule M4); do not edit. Built-in copy of the
// reference model catalog, parsed (core/domain/model-details.ts parseReference) from:
${provenance(["models-opencode-reference.json"])}
import type { ReferenceRecord } from "@accounts-proxy/core/domain/model-details.ts";

export const BUILTIN_REFERENCE: ReferenceRecord = ${JSON.stringify(record, null, 1)};
`,
);
console.log(`model reference: ${[...reference].map(([p, m]) => `${p} ${m.size}`).join(", ")}`);
