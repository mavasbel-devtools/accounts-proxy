// P4 live smoke: the real daemon (`serve` on the proxy's own data directory and accounts) answers each P4 route
// once against the real upstreams. Five small requests: Anthropic messages (no thinking — decision Q6 live) and
// streamed, Gemini generateContent and streamGenerateContent?alt=sse, and the three model lists. The proxy token
// is read from the daemon's `token` command and never printed. Usage:
//   ACCOUNTS_PROXY_LIVE=1 bun scripts/evidence/live/p4-daemon-smoke.ts
import { join } from "node:path";
import { parseProxyConfig } from "@accounts-proxy/core/domain/config.ts";
import { YamlConfigFile } from "@accounts-proxy/proxy/adapters/outbound/yaml-config-file.ts";
import { defaultHome } from "@accounts-proxy/proxy/composition/container.ts";
import { repositoryRoot } from "@accounts-proxy/scripts/gate/instrument.ts";
import { requireLive, sleep, timestamp, writeDoc, openLive } from "@accounts-proxy/scripts/evidence/live/harness.ts";

requireLive();
const live = await openLive();
const entry = join(repositoryRoot, "apps", "proxy", "src", "main", "cli.ts");
const home = defaultHome(process.env, entry);
const port = parseProxyConfig(await new YamlConfigFile(join(home, "proxy.yaml")).read()).port;
const token = (await new Response(Bun.spawn([process.execPath, entry, "token"], { stdout: "pipe" }).stdout).text()).trim();
live.redactor.add("proxy_token", token);

const daemon = Bun.spawn([process.execPath, entry, "serve"], { stdout: "pipe", stderr: "pipe" });
let output = "";
const reading = (async () => {
  for await (const chunk of daemon.stdout) output += new TextDecoder().decode(chunk);
})();
for (let i = 0; i < 500 && !output.includes("listening on"); i++) await sleep(10);
const base = `http://127.0.0.1:${port}`;

type Row = { route: string; status: number; contentType: string; observed: string; ms: number };
const rows: Row[] = [];
async function call(route: string, init: RequestInit, observe: (text: string) => string) {
  const started = performance.now();
  const res = await fetch(`${base}${route}`, init);
  const text = await res.text();
  rows.push({ route, status: res.status, contentType: res.headers.get("content-type") ?? "", observed: live.redactor.text(observe(text)).replaceAll("|", "\\|").replaceAll("\n", " ").slice(0, 300), ms: Math.round(performance.now() - started) });
  await sleep(2000);
}
const anthropic = { "x-api-key": token, "content-type": "application/json", "anthropic-version": "2023-06-01" };
const gemini = { "x-goog-api-key": token, "content-type": "application/json" };
const haiku = { model: "claude/claude-haiku-4-5-20251001", max_tokens: 32, messages: [{ role: "user", content: "Reply with the single word OK." }] };
const hello = JSON.stringify({ contents: [{ role: "user", parts: [{ text: "Reply with the single word OK." }] }] });

await call("/anthropic/v1/messages", { method: "POST", headers: anthropic, body: JSON.stringify(haiku) }, (t) => {
  const m = JSON.parse(t) as { content?: { type: string; text?: string }[]; stop_reason?: string };
  return `stop_reason=${m.stop_reason} content=${JSON.stringify(m.content)}`;
});
await call("/anthropic/v1/messages", { method: "POST", headers: anthropic, body: JSON.stringify({ ...haiku, stream: true }) }, (t) => `events=${t.split("\n").filter((l) => l.startsWith("event:")).map((l) => l.slice(7)).join(",")}`);
await call("/gemini/v1beta/models/antigravity/gemini-3.6-flash-low:generateContent", { method: "POST", headers: gemini, body: hello }, (t) => {
  const r = JSON.parse(t) as { candidates?: { content: { parts: { text?: string }[] }; finishReason?: string }[] };
  return `finish=${r.candidates?.[0]?.finishReason} text=${JSON.stringify(r.candidates?.[0]?.content.parts.map((p) => p.text ?? "").join(""))}`;
});
await call("/gemini/v1beta/models/antigravity%2Fgemini-3.6-flash-low:streamGenerateContent?alt=sse", { method: "POST", headers: gemini, body: hello }, (t) => `frames=${t.split("\r\n\r\n").filter((f) => f.startsWith("data: ")).length}`);
for (const [route, headers] of [
  ["/anthropic/v1/models", anthropic],
  ["/openai/v1/models", { authorization: `Bearer ${token}` }],
  ["/gemini/v1beta/models", gemini],
] as const) {
  await call(route, { headers }, (t) => `${(JSON.parse(t) as { data?: unknown[]; models?: unknown[] }).data?.length ?? (JSON.parse(t) as { models: unknown[] }).models.length} models`);
}

daemon.kill("SIGTERM");
const code = await daemon.exited;
await reading;
const ts = timestamp();
writeDoc(
  live,
  `docs/reference/${ts}-p4-live-daemon-smoke.md`,
  `# P4 live smoke: the daemon against the real accounts

Generated by \`scripts/evidence/live/p4-daemon-smoke.ts\` on ${new Date().toISOString()}: \`serve\` on the proxy's own
data directory, one request per P4 route through raw HTTP, 2 s apart. Daemon exit after SIGTERM: ${code}.

| Route | HTTP | Content-Type | ms | Observed |
|---|---|---|---|---|
${rows.map((r) => `| \`${r.route}\` | ${r.status} | ${r.contentType} | ${r.ms} | ${r.observed} |`).join("\n")}

Daemon output:
\`\`\`
${live.redactor.text(output).trim()}
\`\`\`
`,
);
console.log(rows.map((r) => `${r.status} ${r.route} ${r.observed}`).join("\n"));
console.log(`daemon exit ${code}; wrote docs/reference/${ts}-p4-live-daemon-smoke.md`);
