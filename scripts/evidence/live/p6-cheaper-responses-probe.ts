// P6 finding (docs/plans/2026-10-17-22-59-p6-live-results-plan.md, P6-4): two of three streamed `cheaper-inference`
// Responses answers reached the client in 2–3 reads at once (every answer text read in the same millisecond, right
// after the headers), the third in 26 reads over 391 ms. Is the burst the upstream's or the proxy's? The same request
// goes straight to the upstream (no proxy in between), with the stored key, through the recording transport, which
// times the headers and every chunk. Usage: ACCOUNTS_PROXY_LIVE=1 bun scripts/evidence/live/p6-cheaper-responses-probe.ts
import { PACE_MS, openLive, sleep, timestamp, writeCapture, writeDoc } from "@accounts-proxy/scripts/evidence/live/harness.ts";
import { analyseStream, sseEvents } from "@accounts-proxy/scripts/evidence/live/stream-timing.ts";

const MODEL = "gpt-5.4-nano";
const RUNS = 4;
const PROMPT = "Count from 1 to 40, separated by spaces. Output only the numbers.";

async function main(): Promise<number> {
  const live = await openLive();
  const gateway = live.gateways.find((g) => g.spec.provider === "cheaper-inference");
  if (gateway === undefined) throw new Error("cheaper-inference is not enabled");
  const key = await gateway.session.optionalKey();
  if (key === undefined) throw new Error("cheaper-inference has no stored key");
  live.redactor.add("cheaper_inference_key", key);
  const url = `${gateway.spec.apiBase}${gateway.spec.endpoints["openai-responses"]!.path}`;
  const capturedAt = new Date().toISOString();
  const rows: string[] = [];
  for (let run = 1; run <= RUNS; run++) {
    const mark = live.recorder.mark();
    const response = await live.recorder.send({
      method: "POST",
      url,
      headers: { authorization: `Bearer ${key}`, "content-type": "application/json", accept: "text/event-stream" },
      body: JSON.stringify({ model: MODEL, input: PROMPT, stream: true }),
    });
    for await (const _chunk of response.body) void _chunk;
    const [exchange] = live.recorder.since(mark);
    const reads = exchange!.chunks.map((c) => ({ atMs: c.atMs, text: c.text }));
    const a = analyseStream("openai-responses", sseEvents(reads));
    const id = `cheaper-resp-direct-${run}`;
    writeCapture(live, `tests/fixtures/captures/p0-live/p6/${id}.json`, { id, target: "cheaper-inference", scenario: id, model: MODEL, capturedAt, exchanges: live.recorder.since(mark) });
    const round = (n: number | undefined) => (n === undefined ? "–" : String(Math.round(n)));
    const row = `| ${run} | ${response.status} | ${round(exchange!.headersAtMs)} | ${round(a.firstTokenMs)} | ${round(a.lastEventMs)} | ${reads.length} | ${a.textReads} | ${round(a.textSpanMs)} | ${round(a.maxGapMs)} | ${a.terminal ? "yes" : "no"} | \`tests/fixtures/captures/p0-live/p6/${id}.json\` |`;
    rows.push(row);
    console.log(row);
    await sleep(PACE_MS);
  }
  const ts = timestamp();
  writeDoc(
    live,
    `docs/reference/${ts}-p6-cheaper-responses-probe.md`,
    `# P6 probe: cheaper-inference Responses streams straight from the upstream

Generated by \`scripts/evidence/live/p6-cheaper-responses-probe.ts\` on ${capturedAt} for the P6 finding
([plan](../plans/2026-10-17-22-59-p6-live-results-plan.md), [results](2026-10-18-18-37-p6-live-results.md)). The request
\`{model: "${MODEL}", input: "${PROMPT}", stream: true}\` is sent to \`${url}\` with the stored key, with no proxy in
between; the recording transport times the response headers and every body chunk (ms since the request was sent).

| Run | HTTP | Headers | First answer text | Last event | Chunks | Chunks with answer text | Text span | Max gap | Terminal | Capture |
|---|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}
`,
  );
  console.log(`wrote docs/reference/${ts}-p6-cheaper-responses-probe.md`);
  return 0;
}

process.exit(await main());
